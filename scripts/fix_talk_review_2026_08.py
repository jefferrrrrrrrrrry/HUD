def apply(path: Path, fixes) -> int:
    s = path.read_text(encoding="utf-8")
    bak = ROOT / "_bak_rename_terms" / ("talk_" + path.name)
    if not bak.exists():
        shutil.copy2(path, bak)
    n = 0
    for name, old, new, probe in fixes:
        if probe in s:
            print(f"SKIP {path.name}:{name}（已改）")
            continue
        if old not in s:
            print(f"⚠ MISS {path.name}:{name}")
            continue
        s = s.replace(old, new, 1)
        n += 1
        print(f"OK   {path.name}:{name}")
    path.write_text(s, encoding="utf-8")
    return n


