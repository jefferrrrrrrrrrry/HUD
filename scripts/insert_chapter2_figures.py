def main() -> None:
    for fname, anchor, block in FIGS:
        p = P / fname
        s = p.read_text(encoding="utf-8")
        if block.split("\n")[0] in s:
            print(f"SKIP {fname}（图已插入）")
            continue
        assert anchor in s, f"{fname} 找不到锚点：{anchor[:40]}"
        s = s.replace(anchor, block + anchor, 1)
        p.write_text(s, encoding="utf-8")
        print(f"FIG  {fname} <- {block.split('](')[1].split(')')[0]}")

    for fname, old, new in FIXES:
        p = P / fname
        s = p.read_text(encoding="utf-8")
        if old not in s:
            print(f"SKIP {fname}: {old[:38]}…（已处理或不存在）")
            continue
        # 插入型改写（new 里含 old）非幂等：new 的首行若已在文中，说明上轮已插过。
        # 缺这一判定会导致每跑一次就多插一份，正文里出现重复段落。
        first = new.split("\n")[0]
        if first != old and first in s:
            print(f"SKIP {fname}: {first[:38]}…（已插入）")
            continue
        p.write_text(s.replace(old, new, 1), encoding="utf-8")
        print(f"FIX  {fname}: {old[:38]}…")


if __name__ == "__main__":
    main()
