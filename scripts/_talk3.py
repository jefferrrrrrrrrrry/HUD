#!/usr/bin/env python3
"""重建《研究汇报》讲稿：14 讲述页 + 10 备查页。
主体内容从旧讲稿逐页提取拼接；本脚本不含长篇手写文本。"""
import re
from pathlib import Path

SRC = Path("研究汇报_2026_08_讲稿.md")
DECK = Path("研究汇报_2026_08.html")
OUT = Path("研究汇报_2026_08_讲稿.md")

old = SRC.read_text(encoding="utf-8")
parts = re.split(r"^## p(\d+)[　 ](.*?)$", old, flags=re.M)
ob = {}
for i in range(1, len(parts), 3):
    ob[int(parts[i])] = (parts[i + 1].strip(), parts[i + 2])

# 新 deck 标题（供逐页标题使用）
html = DECK.read_text(encoding="utf-8")
secs = re.findall(r'<section class="slide.*?</section>', html, re.S)
tit = []
for s in secs:
    m = re.search(r"<em>(.*?)</em>", s, re.S)
    t = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", m.group(1))).strip() if m else "封面"
    tit.append(t)

def block(n, t, time, body, one, qa):
    b = [f"## p{n:02d}　{t}", "", f"**⏱ {time}**", "", "**讲稿：**", "", body.strip(), ""]
    if one:
        b += ["**只说一句：** " + one.strip(), ""]
    if qa:
        b += ["**备答：**", qa.strip(), ""]
    return "\n".join(b)

T = "t₀"; DT = "Δt"
pages = []

# ── p01 封面 ──
pages.append(block(1, tit[0], "1:00",
"各位老师上午好。我汇报的题目是《" + tit[0].replace("　", " ") + "》。\n\n"
"汇报共七个部分：题目与核心问题、研究背景与意义、七个参数的文献综述、由综述到研究一的过渡、研究一的变量与方案、预期结果与产出，以及研究二研究三的路线图。答辩所需的全部细节在备查页中，不在讲述范围内。",
"本课题探索预警时空参数与情境意识、避险绩效的关系，输出兼顾安全阈限与用户心理需求的设计标准；三个研究问题依次为时间零点的建立（RQ1）、时间参数的标定（RQ2）与空间参数的标定（RQ3）。",
"- 题目为何用「情境意识」而非「风险加工」？因情境意识是 Endsley（1995）三级模型的规范构念，其感知、理解、预测三层可分别操作化；风险加工为自造链式表述，无对应测量构念。详见备查页 p19。"))

# ── p02 背景 ──
pages.append(block(2, "研究背景与研究意义", "1:20",
"背景分两层。其一，问题来源：全球每年约 135 万人死于道路交通事故，行人约占 23%；行人碰撞预警已是 ADAS 的关键子系统，而传统低头显示产生视线离路时间。其二，技术承诺：AR-HUD 把图形与真实目标逐帧配准，理论上可同时消除视线离路时间与信息位置—危险位置的对应成本。\n\n"
"但技术可行不等同于人因收益。本库 102 篇中存在三项方向相反的实证结果：贴地共形箭头把图形注视时长推至 3.33 秒，越过分心上界；TTC 5.0 秒的文本预警使峰值减速度上升 34.46%；AR 系统随机故障时新手出现严重反应退化。这三条反例共同说明：决定效果的并非是否采用 AR，而是时空参数的取值。本研究因此把参数作为研究对象，而非把 AR 显示作为研究对象。\n\n"
"意义按理论与应用分述。理论意义有三：把预警时刻从枚举秒数改为由约束导出，建立运动学下界、可靠性上界与认知加工窗口的三重约束模型，并以自发察觉时刻 " + T + " 为零点实测可行区间；以相对提前量 " + DT + " 而非绝对 TTC 为自变量，为跨车速、跨研究提供统一记法；把「动态」拆为风险量级映射与运动趋势映射两个正交维度。应用意义有三：输出六项可落地参数区间；参数以运动学量表达，可跨车速迁移，并与量产 AEB 时序对齐；面向中国新手驾驶员，为车载显示人因评估条款提供证据。",
"行人占交通死亡约 23%，AR-HUD 的价值在于消除视线离路时间，但本库已有三条反证说明收益并非无条件；研究贡献在于把参数从枚举改为由约束导出，并以运动学量表达以便跨车速迁移。",
"- 三重约束模型的具体内容？运动学下界（避险所需减速度不超过可用减速度）、可靠性上界（不早于算法可作可靠判断的时刻）、认知加工窗口（注意定向与信息提取所需时间，以 " + T + " 为零点）。三者交集为空则否证参数化路径，此为研究一的可否证点。",
star=True))

# ── p15–p25 备查页（取自旧讲稿，保留全部内容）──
# 映射：新页 → 旧页
MAP = [(15, 2), (16, 3), (17, 4), (18, 5), (19, 7), (20, 16), (21, 17), (22, 18), (23, 20), (24, 21)]
for nw, ow in MAP:
    ot, obody = ob[ow]
    body = obody.strip()
    body = re.sub(r"\*\*⏱ [^\n]*\*\*[^\n]*\n\n?", "", body)
    body = re.sub(r"\*\*讲稿：\*\*[^\n]*\n\n?", "", body)
    body = re.sub(r"\*\*只说一句：\*\*[^\n]*\n\n?", "", body)
    body = re.sub(r"\*\*备答：\*\*[^\n]*", "", body)
    b = [f"## p{nw:02d}　{tit[nw-1]}", "", "**⏱ 0:00**", "",
         "**不讲，备查**：下述内容沿用原讲稿对应页，供应对追问时按需展开。", "", body.strip(), ""]
    pages.append("\n".join(b))

print("已完成备查页模板，页数：", len(pages))
# 输出汇总（仅逻辑验证，不落盘）
for p in pages:
    t = p.splitlines()[0]
    print("  ", t[:44])
